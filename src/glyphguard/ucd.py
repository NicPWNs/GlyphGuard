"""Unicode character properties from GlyphGuard's vendored, version-pinned tables.

The standard library's :mod:`unicodedata` is tied to the interpreter's Unicode version
and has no Script property, so GlyphGuard ships its own tables (generated by
``scripts/gen_data.py``). :mod:`unicodedata` is only used for character names.
"""

from __future__ import annotations

import unicodedata
from bisect import bisect_right
from functools import lru_cache

from glyphguard._data import ucd as _t

UNICODE_VERSION: str = _t.UNICODE_VERSION
"""Version of the Unicode Character Database the tables were generated from."""

_TAG_BASE = 0xE0000
MAX_CODE_POINT = 0x10FFFF


def _in(boundaries: tuple[int, ...], cp: int) -> bool:
    return bisect_right(boundaries, cp) % 2 == 1


def category_ranges(categories: frozenset[str] | set[str]) -> list[tuple[int, int]]:
    """Inclusive code point ranges whose General_Category is in ``categories``."""
    starts = _t.GENERAL_CATEGORY_STARTS
    ends = (*starts[1:], MAX_CODE_POINT + 1)
    return [
        (start, end - 1)
        for start, end, value in zip(starts, ends, _t.GENERAL_CATEGORY_VALUES, strict=True)
        if _t.GENERAL_CATEGORY_NAMES[value] in categories
    ]


def property_ranges(name: str) -> list[tuple[int, int]]:
    """Inclusive ranges of a binary property, e.g. ``"DEFAULT_IGNORABLE"``, ``"WHITE_SPACE"``."""
    boundaries: tuple[int, ...] = getattr(_t, name)
    return [(boundaries[k], boundaries[k + 1] - 1) for k in range(0, len(boundaries), 2)]


@lru_cache(maxsize=4096)
def general_category(cp: int) -> str:
    """Two-letter General_Category, e.g. ``"Lu"``, ``"Cf"`` or ``"Cn"`` (unassigned)."""
    index = bisect_right(_t.GENERAL_CATEGORY_STARTS, cp) - 1
    return _t.GENERAL_CATEGORY_NAMES[_t.GENERAL_CATEGORY_VALUES[index]]


@lru_cache(maxsize=4096)
def script(cp: int) -> str:
    """Script property value, e.g. ``"Latin"``, ``"Cyrillic"``, ``"Common"``, ``"Inherited"``."""
    index = bisect_right(_t.SCRIPT_STARTS, cp) - 1
    return _t.SCRIPT_NAMES[_t.SCRIPT_VALUES[index]]


@lru_cache(maxsize=4096)
def script_extensions(cp: int) -> frozenset[str]:
    """Script_Extensions property: the scripts a character is used with."""
    value = _t.SCRIPT_EXTENSION_VALUES[bisect_right(_t.SCRIPT_EXTENSION_STARTS, cp) - 1]
    if value == 0:
        return frozenset((script(cp),))
    return frozenset(_t.SCRIPT_NAMES[i] for i in _t.SCRIPT_EXTENSION_SETS[value - 1])


# Control characters have no Name property; use their formal aliases instead.
_CONTROL_NAMES = dict(
    enumerate(
        [
            "NULL",
            "START OF HEADING",
            "START OF TEXT",
            "END OF TEXT",
            "END OF TRANSMISSION",
            "ENQUIRY",
            "ACKNOWLEDGE",
            "ALERT",
            "BACKSPACE",
            "CHARACTER TABULATION",
            "LINE FEED",
            "LINE TABULATION",
            "FORM FEED",
            "CARRIAGE RETURN",
            "SHIFT OUT",
            "SHIFT IN",
            "DATA LINK ESCAPE",
            "DEVICE CONTROL ONE",
            "DEVICE CONTROL TWO",
            "DEVICE CONTROL THREE",
            "DEVICE CONTROL FOUR",
            "NEGATIVE ACKNOWLEDGE",
            "SYNCHRONOUS IDLE",
            "END OF TRANSMISSION BLOCK",
            "CANCEL",
            "END OF MEDIUM",
            "SUBSTITUTE",
            "ESCAPE",
            "INFORMATION SEPARATOR FOUR",
            "INFORMATION SEPARATOR THREE",
            "INFORMATION SEPARATOR TWO",
            "INFORMATION SEPARATOR ONE",
        ]
    )
) | {
    0x7F: "DELETE",
    0x85: "NEXT LINE",
    0x90: "DEVICE CONTROL STRING",
    0x98: "START OF STRING",
    0x9B: "CONTROL SEQUENCE INTRODUCER",
    0x9C: "STRING TERMINATOR",
    0x9D: "OPERATING SYSTEM COMMAND",
    0x9E: "PRIVACY MESSAGE",
    0x9F: "APPLICATION PROGRAM COMMAND",
}


def name(cp: int) -> str:
    """Character name, or a descriptive label when the name is unavailable."""
    found = unicodedata.name(chr(cp), "") or _CONTROL_NAMES.get(cp, "")
    if found:
        return found
    if _TAG_BASE <= cp <= 0xE007F:
        return f"TAG {cp - _TAG_BASE:#04x}"
    if 0xE0100 <= cp <= 0xE01EF:
        return f"VARIATION SELECTOR-{cp - 0xE0100 + 17}"
    category = general_category(cp)
    label = {
        "Cn": "UNASSIGNED" if not is_noncharacter(cp) else "NONCHARACTER",
        "Co": "PRIVATE USE",
        "Cs": "SURROGATE",
        "Cc": "CONTROL",
    }.get(category, "CHARACTER")
    return f"<{label}-{cp:04X}>"


def label(cp: int) -> str:
    """``U+XXXX NAME`` label used in findings and reports."""
    return f"U+{cp:04X} {name(cp)}"


def is_default_ignorable(cp: int) -> bool:
    return _in(_t.DEFAULT_IGNORABLE, cp)


def is_bidi_control(cp: int) -> bool:
    return _in(_t.BIDI_CONTROL, cp)


def is_white_space(cp: int) -> bool:
    return _in(_t.WHITE_SPACE, cp)


def is_noncharacter(cp: int) -> bool:
    return _in(_t.NONCHARACTER, cp)


def is_variation_selector(cp: int) -> bool:
    return _in(_t.VARIATION_SELECTOR, cp)


def is_join_control(cp: int) -> bool:
    return _in(_t.JOIN_CONTROL, cp)


def is_extended_pictographic(cp: int) -> bool:
    return _in(_t.EXTENDED_PICTOGRAPHIC, cp)


def is_emoji_modifier(cp: int) -> bool:
    return _in(_t.EMOJI_MODIFIER, cp)


def is_emoji_component(cp: int) -> bool:
    return _in(_t.EMOJI_COMPONENT, cp)


def is_overlay_mark(cp: int) -> bool:
    """Canonical_Combining_Class 1 (Overlay): marks drawn through their base."""
    return _in(_t.OVERLAY_MARK, cp)


def is_mark(cp: int) -> bool:
    return general_category(cp) in ("Mn", "Me", "Mc")


def is_combining(cp: int) -> bool:
    """A combining mark other than a variation selector (which are also category Mn)."""
    return is_mark(cp) and not is_variation_selector(cp)


def is_tag(cp: int) -> bool:
    return _TAG_BASE <= cp <= 0xE007F


def is_valid_variation_sequence(base: int, selector: int) -> bool:
    """True if ``base + selector`` is a standardized or emoji variation sequence."""
    return (base << 21) | selector in _t.VARIATION_SEQUENCES


def is_regional_indicator(cp: int) -> bool:
    return 0x1F1E6 <= cp <= 0x1F1FF


def is_ideograph(cp: int) -> bool:
    """Han characters, the bases that Ideographic Variation Sequences attach to."""
    return script(cp) == "Han" and general_category(cp) == "Lo"
